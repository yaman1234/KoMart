const fs = require('fs');
const path = require('path');

const context = process.env.CONTEXT || '';
const branch = process.env.BRANCH || '';

// Production builds (main branch) use Vercel backend.
// UAT, branch deploys, and previews use Render backend.
const isProduction = context === 'production' || branch === 'main' || branch === 'master';

const backendUrl =
  process.env.BACKEND_PROXY_URL ||
  (isProduction ? 'https://ko-mart.vercel.app' : 'https://komart.onrender.com');

const redirectsContent = `# Auto-generated by generate-redirects.cjs
# Context: ${context || 'local'} | Branch: ${branch || 'local'} | Target: ${backendUrl}

/api/*  ${backendUrl}/api/:splat  200!
/*      /index.html               200
`;

const destPath = path.resolve(__dirname, '../public/_redirects');
fs.writeFileSync(destPath, redirectsContent, 'utf-8');
console.log(`[generate-redirects] Configured /api proxy -> ${backendUrl} (${isProduction ? 'Production' : 'UAT/Preview'})`);
