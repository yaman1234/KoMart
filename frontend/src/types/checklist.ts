export type ChecklistCategory =
  | 'opening'
  | 'mid_day'
  | 'closing'
  | 'hygiene_safety'
  | 'inventory'
  | 'general';

export type TargetRole = 'cashier' | 'manager' | 'all';

export type ChecklistStatus = 'pending' | 'in_progress' | 'completed';

export interface TemplateItem {
  id: string;
  title: string;
  description?: string;
  isMandatory: boolean;
  order: number;
  requiresNumericInput: boolean;
  numericUnit?: string;
  requiresNote: boolean;
}

export interface ChecklistTemplate {
  id: string;
  title: string;
  description?: string;
  category: ChecklistCategory;
  targetRole: TargetRole;
  shiftId?: string;
  shiftName?: string;
  items: TemplateItem[];
  isActive: boolean;
  autoGenerateDaily: boolean;
  daysOfWeek: number[];
  createdBy: string;
  createdByName: string;
  createdAt: string;
  updatedAt: string;
}

export interface DailyChecklistItem {
  id: string;
  title: string;
  description?: string;
  isMandatory: boolean;
  order: number;
  isCompleted: boolean;
  completedByUserId?: string;
  completedByName?: string;
  completedAt?: string;
  numericInput?: number;
  numericUnit?: string;
  notes?: string;
}

export interface DailyChecklist {
  id: string;
  templateId?: string;
  title: string;
  description?: string;
  category: ChecklistCategory;
  date: string;
  targetRole: TargetRole;
  assignedToUserId?: string;
  assignedToUserName?: string;
  assignedByUserId?: string;
  assignedByUserName?: string;
  shiftId?: string;
  shiftName?: string;
  items: DailyChecklistItem[];
  totalItemsCount: number;
  completedItemsCount: number;
  completionRate: number;
  status: ChecklistStatus;
  requiresManagerVerification: boolean;
  verifiedByUserId?: string;
  verifiedByName?: string;
  verifiedAt?: string;
  managerRemarks?: string;
  completedAt?: string;
  createdAt: string;
  updatedAt: string;
}

export interface ChecklistItemToggleRequest {
  isCompleted: boolean;
  numericInput?: number;
  notes?: string;
}

export interface ChecklistVerifyRequest {
  remarks?: string;
}

